/*
  # Create adaptation_log table

  ## Summary
  Stores every adaptation suggestion generated by the microcycle adaptation engine.
  Keeps a full audit trail of what was proposed, why, and what was applied.
  Adaptations MODIFY existing ATP week overrides — they never generate new plans.

  ## New Tables
  - `adaptation_log`
    - `id` (uuid, PK)
    - `athlete_id` (text NOT NULL) — hub_user_id
    - `plan_id` (uuid, FK → atp_plans.id, nullable) — null if no ATP plan
    - `week_number` (int) — which week this adapts (0-indexed, matches atp_week_overrides)
    - `week_start_date` (date)
    - `trigger_reason` (text) — what triggered this adaptation: 'post_workout' | 'weekly_review' | 'manual'
    - `rule_id` (text) — which rule fired: e.g. 'FATIGUE_HIGH', 'LOAD_UNDERACHIEVEMENT', etc.
    - `rule_label` (text) — human label for the rule
    - `previous_impulse` (numeric) — planned impulse before adaptation
    - `proposed_impulse` (numeric) — new proposed weekly impulse
    - `load_delta_pct` (numeric) — % change proposed
    - `rationale` (text) — explanation for athlete/coach
    - `safety_flags` (jsonb) — any safety constraints triggered
    - `status` (text) — 'pending' | 'approved' | 'dismissed'
    - `applied_at` (timestamptz, nullable)
    - `input_snapshot` (jsonb) — full state snapshot at time of analysis
    - `created_at` (timestamptz)

  ## Security
  - RLS enabled
  - Athletes/coaches can read own records; anon allowed for Hub-auth pattern
*/

CREATE TABLE IF NOT EXISTS adaptation_log (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  athlete_id text NOT NULL,
  plan_id uuid REFERENCES atp_plans(id) ON DELETE SET NULL,
  week_number integer NOT NULL DEFAULT 0,
  week_start_date date,
  trigger_reason text NOT NULL DEFAULT 'post_workout'
    CHECK (trigger_reason IN ('post_workout', 'weekly_review', 'manual')),
  rule_id text NOT NULL,
  rule_label text NOT NULL,
  previous_impulse numeric(10,3) NOT NULL DEFAULT 0,
  proposed_impulse numeric(10,3) NOT NULL DEFAULT 0,
  load_delta_pct numeric(6,2) NOT NULL DEFAULT 0,
  rationale text NOT NULL DEFAULT '',
  safety_flags jsonb,
  status text NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'approved', 'dismissed')),
  applied_at timestamptz,
  input_snapshot jsonb,
  created_at timestamptz DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_adaptation_log_athlete_id ON adaptation_log(athlete_id);
CREATE INDEX IF NOT EXISTS idx_adaptation_log_plan_id ON adaptation_log(plan_id);
CREATE INDEX IF NOT EXISTS idx_adaptation_log_week_start ON adaptation_log(week_start_date DESC);
CREATE INDEX IF NOT EXISTS idx_adaptation_log_status ON adaptation_log(status);

ALTER TABLE adaptation_log ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Authenticated users can read own adaptation log"
  ON adaptation_log
  FOR SELECT
  TO authenticated
  USING (athlete_id = auth.uid()::text);

CREATE POLICY "Anonymous users can read adaptation log"
  ON adaptation_log
  FOR SELECT
  TO anon
  USING (true);

CREATE POLICY "Anonymous users can insert adaptation log"
  ON adaptation_log
  FOR INSERT
  TO anon
  WITH CHECK (true);

CREATE POLICY "Authenticated users can insert own adaptation log"
  ON adaptation_log
  FOR INSERT
  TO authenticated
  WITH CHECK (athlete_id = auth.uid()::text);

CREATE POLICY "Anonymous users can update adaptation log"
  ON adaptation_log
  FOR UPDATE
  TO anon
  USING (true)
  WITH CHECK (true);

CREATE POLICY "Authenticated users can update own adaptation log"
  ON adaptation_log
  FOR UPDATE
  TO authenticated
  USING (athlete_id = auth.uid()::text)
  WITH CHECK (athlete_id = auth.uid()::text);
